// Explains one metric from /api/me/metrics: its real value, the exact definition used in
// src/lib/metrics/compute.ts, the records it was computed from, and advice derived from the
// student's own numbers. Nothing here is generated by a model.

export type MetricId =
  | "percentile"
  | "accuracy"
  | "speed"
  | "negativeMarking"
  | "dailyAverage"
  | "weeklyVolume"
  | "consistency"
  | "streak";

interface MetricInspectorModalProps {
  metricId: MetricId | null;
  metrics: StudentMetrics;
  /** Window used by the page's daily-average card (7 or 30 days). */
  windowDays: 7 | 30;
  onClose: () => void;
  onDrillAction?: (topicId: string, topicTitle: string) => void;
}

type StatusType = "success" | "warning" | "info" | "danger";
type Cell = string | { text: string; tone?: "correct" | "incorrect"; strong?: boolean };

interface MetricView {
  name: string;
  icon: string;
  benchmark: string;
  statusText: string;
  statusType: StatusType;
  value: string;
  valueNote: string;
  formula: string;
  explanation: string;
  calc: string;
  tableIntro: string;
  columns: string[];
  rows: Cell[][];
  totalRow?: Cell[];
  emptyTable: string;
  advice: string[];
  action?: { label: string; topicId: string; topicTitle: string };
}

const SECTIONS: SectionKey[] = ["VARC", "DILR", "QA"];
const TIMED_KINDS = new Set<TestRecord["kind"]>(["pyq", "module_quiz", "grand_quiz"]);
// Pace-index anchors and the active-day threshold, as defined in src/lib/metrics/compute.ts.
const SPEED_BEST = 90;
const SPEED_WORST = 240;
const MIN_ACTIVE_SECONDS = 120;
const SECTION_SECONDS = 40 * 60;

function fmtDuration(seconds: number): string {
  const mins = Math.round(seconds / 60);
  if (mins < 60) return `${mins}m`;
  const h = Math.floor(mins / 60);
  const m = mins % 60;
  return m ? `${h}h ${String(m).padStart(2, "0")}m` : `${h}h`;
}

function fmtPace(seconds: number): string {
  if (seconds < 60) return `${seconds}s`;
  const m = Math.floor(seconds / 60);
  const s = seconds % 60;
  return s ? `${m}m ${s}s` : `${m}m`;
}

function fmtDate(iso: string): string {
  return new Date(iso).toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric" });
}

function fmtDay(ymd: string): string {
  return new Date(`${ymd}T00:00:00Z`).toLocaleDateString("en-IN", { weekday: "short", day: "numeric", month: "short", timeZone: "UTC" });
}

const dayTotal = (d: DailyStudy) => d.learningSeconds + d.practiceSeconds;

function drillFor(metrics: StudentMetrics, section: SectionKey | null): MetricView["action"] {
  if (!section) return undefined;
  const topic = metrics.courses.topics.find((t) => t.section === section);
  return topic ? { label: `Drill ${section}`, topicId: topic.topicId, topicTitle: topic.title } : undefined;
}

function weakestSectionByAccuracy(metrics: StudentMetrics): SectionKey | null {
  const withData = SECTIONS.filter((s) => metrics.sections[s].accuracy !== null && metrics.sections[s].attempted > 0);
  if (withData.length < 2) return null;
  return withData.reduce((a, b) => (metrics.sections[a].accuracy! <= metrics.sections[b].accuracy! ? a : b));
}

function dayRows(days: DailyStudy[]): Cell[][] {
  return [...days].reverse().map((d) => [
    { text: fmtDay(d.date), strong: true },
    fmtDuration(d.learningSeconds),
    fmtDuration(d.practiceSeconds),
    fmtDuration(dayTotal(d)),
    dayTotal(d) >= MIN_ACTIVE_SECONDS ? { text: "Active", tone: "correct" } : { text: "Inactive", tone: "incorrect" },
  ]);
}

const DAY_COLUMNS = ["Date", "Learning", "Practice", "Total", "Day status"];

function buildView(id: MetricId, m: StudentMetrics, windowDays: 7 | 30): MetricView {
  const a = m.accuracy;
  switch (id) {
    case "percentile": {
      const p = m.percentile;
      const est = p.overallEstimate;
      const maxTotal = SECTIONS.reduce((s, k) => s + m.sections[k].maxScore, 0);
      const missing = SECTIONS.filter((s) => m.sections[s].latestScore === null);
      const withEst = SECTIONS.filter((s) => m.sections[s].estimatedPercentile !== null);
      const advice: string[] = [];
      for (const s of missing) {
        advice.push(`Attempt a full ${s} PYQ section (${m.sections[s].maxScore} marks) to get a ${s} estimate${est === null ? " and unlock the overall estimate" : ""}.`);
      }
      if (withEst.length >= 2) {
        const low = withEst.reduce((x, y) => (m.sections[x].estimatedPercentile! <= m.sections[y].estimatedPercentile! ? x : y));
        advice.push(
          `${low} is your lowest section estimate (${m.sections[low].estimatedPercentile} %ile from a latest score of ${m.sections[low].latestScore}/${m.sections[low].maxScore}). Prioritise it in your next practice block.`
        );
      }
      advice.push("Treat estimates as a direction, not a prediction: they use approximate public CAT 2024 trends, not official data.");
      return {
        name: "Estimated CAT Percentile",
        icon: "target",
        benchmark: "Needs one full PYQ section in each of VARC, DILR and QA",
        statusText: est !== null ? "Estimated" : "Not enough data",
        statusType: est !== null ? "info" : "warning",
        value: est !== null ? `${est} %ile` : "Not available yet",
        valueNote: est !== null ? `Estimated from an overall score of ${p.overallScore} / ${maxTotal}. ${p.disclaimer}` : p.basis,
        formula: "Overall score = latest VARC + DILR + QA full-section PYQ scores  →  estimated percentile (interpolated on a reference score-vs-percentile curve)",
        explanation:
          "Each PYQ section is scored with CAT marking: +3 for a correct answer, −1 for a wrong MCQ, 0 for a wrong TITA or an unanswered question. Only full sections (VARC 72, DILR 66, QA 66 marks) get a section estimate. " +
          p.disclaimer,
        calc:
          est !== null
            ? `VARC ${m.sections.VARC.latestScore} + DILR ${m.sections.DILR.latestScore} + QA ${m.sections.QA.latestScore} = ${p.overallScore} marks  →  about ${est} %ile (estimated)`
            : `Missing a full PYQ section in: ${missing.join(", ")}. ${p.basis}`,
        tableIntro: "Your latest and best full-section PYQ scores per section:",
        columns: ["Section", "PYQ attempts", "Latest score", "Best score", "Est. section %ile"],
        rows: SECTIONS.map((s) => {
          const x = m.sections[s];
          return [
            { text: s, strong: true },
            String(x.pyqAttempts),
            x.latestScore !== null ? `${x.latestScore} / ${x.maxScore}` : "—",
            x.bestScore !== null ? `${x.bestScore} / ${x.maxScore}` : "—",
            x.estimatedPercentile !== null ? `${x.estimatedPercentile} (est.)` : "—",
          ];
        }),
        emptyTable: "",
        advice,
      };
    }

    case "accuracy": {
      const weakSection = weakestSectionByAccuracy(m);
      const advice: string[] = [];
      if (a.overall === null) {
        advice.push(`You have answered ${a.attempted} question${a.attempted === 1 ? "" : "s"} in timed tests. Take a module quiz or a PYQ section to reach the 5 needed for an accuracy figure.`);
      }
      if (weakSection) {
        const s = m.sections[weakSection];
        advice.push(`${weakSection} is your least accurate section (${s.accuracy}% on ${s.attempted} answers). Review its weak concepts before your next timed test.`);
      }
      if (m.concepts.weak.length) {
        advice.push(
          `Concepts below 60%: ${m.concepts.weak
            .slice(0, 3)
            .map((c) => `${c.concept} (${c.accuracy}% on ${c.attempted})`)
            .join(", ")}.`
        );
      }
      if (m.concepts.strong.length) {
        advice.push(`Strongest concepts: ${m.concepts.strong.slice(0, 3).map((c) => `${c.concept} (${c.accuracy}%)`).join(", ")}. Keep them warm with occasional mixed practice.`);
      }
      const status: [string, StatusType] =
        a.overall === null ? ["Pending", "warning"] : a.overall >= 80 ? ["Strong", "success"] : a.overall >= 60 ? ["Moderate", "info"] : ["Needs work", "danger"];
      return {
        name: "Overall Accuracy",
        icon: "trend",
        benchmark: "Timed tests only: PYQ sections, module quizzes and grand quizzes",
        statusText: status[0],
        statusType: status[1],
        value: a.overall !== null ? `${a.overall}%` : "Not available yet",
        valueNote:
          a.overall !== null
            ? `${a.correct} correct of ${a.attempted} answered questions.`
            : `${a.attempted} answered so far. At least 5 answered questions are needed.`,
        formula: "Accuracy = correct answers ÷ answered questions × 100",
        explanation:
          "Counts only questions you answered in timed tests (PYQ sections, module and grand quizzes). Skipped questions are excluded, and untimed lesson practice is not included. Shown once at least 5 questions have been answered.",
        calc: a.overall !== null ? `${a.correct} ÷ ${a.attempted} × 100 = ${a.overall}%` : `${a.correct} correct of ${a.attempted} answered (fewer than 5, so no figure yet).`,
        tableIntro: "Answered questions by section (timed tests):",
        columns: ["Section", "Answered", "Correct", "Wrong", "Accuracy"],
        rows: SECTIONS.map((s) => {
          const x = m.sections[s];
          return [
            { text: s, strong: true },
            String(x.attempted),
            { text: `+${x.correct}`, tone: "correct" },
            { text: `-${x.attempted - x.correct}`, tone: "incorrect" },
            x.accuracy !== null ? `${x.accuracy}%` : "—",
          ];
        }),
        totalRow: [
          { text: "All timed tests", strong: true },
          { text: String(a.attempted), strong: true },
          { text: `+${a.correct}`, tone: "correct" },
          { text: `-${a.wrong}`, tone: "incorrect" },
          { text: a.overall !== null ? `${a.overall}%` : "—", strong: true },
        ],
        emptyTable: "",
        advice,
        action: drillFor(m, weakSection ?? m.concepts.weak[0]?.section ?? null),
      };
    }

    case "speed": {
      const spq = m.speed.secondsPerQuestion;
      const bench = m.speed.benchmarkSecondsPerQuestion;
      const timed = m.tests.recent.filter((t) => TIMED_KINDS.has(t.kind) && t.secondsPerQuestion !== null);
      const advice: string[] = [];
      if (spq === null) {
        advice.push("Take a timed test (a PYQ section or a module quiz) to measure your pace.");
      } else {
        const yours = Math.floor(SECTION_SECONDS / spq);
        const cat = Math.floor(SECTION_SECONDS / bench);
        if (spq > bench) {
          advice.push(`You take ${spq - bench}s more per question than CAT pace. At your pace you reach about ${yours} questions in a 40-minute section, versus ${cat} at CAT pace.`);
        } else {
          advice.push(`You are at or faster than CAT pace (about ${yours} questions per 40-minute section). Make sure speed is not costing accuracy${a.overall !== null ? ` (currently ${a.overall}%)` : ""}.`);
        }
      }
      const bySection = SECTIONS.map((s) => {
        const ts = timed.filter((t) => t.section === s);
        const secs = ts.reduce((x, t) => x + t.durationSeconds, 0);
        const n = ts.reduce((x, t) => x + t.attempted, 0);
        return { s, pace: n > 0 ? Math.round(secs / n) : null };
      }).filter((x) => x.pace !== null);
      if (bySection.length >= 2) {
        const slow = bySection.reduce((x, y) => (x.pace! >= y.pace! ? x : y));
        advice.push(`In your recent timed tests, ${slow.s} is your slowest section at ${fmtPace(slow.pace!)} per question.`);
      }
      return {
        name: "Pace (Time per Question)",
        icon: "bolt",
        benchmark: `CAT pace: ${bench}s per question (120 minutes ÷ 66 questions)`,
        statusText: spq === null ? "Pending" : spq <= bench ? "At CAT pace" : spq <= bench * 1.25 ? "Slightly slow" : "Slower than CAT pace",
        statusType: spq === null ? "warning" : spq <= bench ? "success" : spq <= bench * 1.25 ? "info" : "warning",
        value: spq !== null ? `${fmtPace(spq)} / Q` : "Not available yet",
        valueNote: spq !== null ? `Pace index ${m.speed.index}/100. CAT pace is ${bench}s per question.` : "Take a timed test to measure your pace.",
        formula: `Pace = total time in timed tests ÷ questions answered.   Pace index = (${SPEED_WORST} − pace) ÷ (${SPEED_WORST} − ${SPEED_BEST}) × 100, limited to 0–100`,
        explanation: `Uses PYQ sections, module quizzes and grand quizzes that recorded a duration. ${SPEED_BEST}s per question or faster scores 100 on the index; ${SPEED_WORST}s or slower scores 0. The pace index is one input to your readiness score.`,
        calc:
          spq !== null
            ? `${spq}s per question  →  (${SPEED_WORST} − ${spq}) ÷ ${SPEED_WORST - SPEED_BEST} × 100 = ${m.speed.index} (after limiting to 0–100)`
            : "No timed test with a recorded duration yet.",
        tableIntro: "Your most recent timed tests (the pace above uses all of them):",
        columns: ["Test", "Date", "Answered", "Time", "Pace"],
        rows: timed.slice(0, 10).map((t) => [{ text: t.title, strong: true }, fmtDate(t.submittedAt), String(t.attempted), fmtDuration(t.durationSeconds), `${fmtPace(t.secondsPerQuestion!)} / Q`]),
        emptyTable: "No timed tests yet. Take a PYQ section or a module quiz.",
        advice,
      };
    }

    case "negativeMarking": {
      const n = a.negativeMarksLost;
      const pyq = m.tests.pyq;
      const answered = pyq.reduce((s, t) => s + t.attempted, 0);
      const wrong = pyq.reduce((s, t) => s + t.wrong, 0);
      const advice: string[] = [];
      if (!pyq.length) {
        advice.push("Attempt a PYQ section to see how many marks negative marking costs you.");
      } else {
        if (answered > 0) advice.push(`${Math.round((wrong / answered) * 100)}% of your answered PYQ questions were wrong (${wrong} of ${answered}, MCQ and TITA).`);
        if (n > 0) advice.push(`Without these negatives, your PYQ section totals would be ${n} mark${n === 1 ? "" : "s"} higher. A skipped MCQ costs nothing; a wrong one costs 1.`);
        else advice.push("No negative marks so far. Keep answering MCQs only when you can eliminate to a confident choice.");
      }
      const byConcept: Record<string, number> = {};
      for (const x of m.mistakes) if (x.marksLost > 0 && x.concept) byConcept[x.concept] = (byConcept[x.concept] || 0) + x.marksLost;
      const top = Object.entries(byConcept).sort((x, y) => y[1] - x[1]).slice(0, 3);
      if (top.length) advice.push(`In your recent mistakes, negative marks came most from: ${top.map(([c, k]) => `${c} (${k})`).join(", ")}.`);
      return {
        name: "Negative Marks Lost",
        icon: "alert",
        benchmark: "CAT marking: +3 correct, −1 wrong MCQ, no penalty for TITA",
        statusText: !pyq.length ? "Pending" : n === 0 ? "No negatives" : "Marks lost",
        statusType: !pyq.length ? "warning" : n === 0 ? "success" : "danger",
        value: pyq.length ? `−${n} marks` : "No PYQ sections yet",
        valueNote: pyq.length ? `${n} wrong MCQ answer${n === 1 ? "" : "s"} across ${pyq.length} PYQ section${pyq.length === 1 ? "" : "s"}, −1 mark each.` : "Attempt a PYQ section to start tracking.",
        formula: "Negative marks lost = wrong MCQ answers in PYQ sections × 1",
        explanation: "This count covers PYQ sections only, which use CAT marking. Wrong TITA answers and unanswered questions cost nothing.",
        calc: `${n} wrong MCQs × (−1) = −${n} marks`,
        tableIntro: "Your PYQ sections. The Wrong column includes TITA answers, which carry no penalty.",
        columns: ["PYQ section", "Date", "Correct", "Wrong (MCQ + TITA)", "Score"],
        rows: pyq.slice(0, 15).map((t) => [
          { text: t.title, strong: true },
          fmtDate(t.submittedAt),
          { text: `+${t.correct}`, tone: "correct" },
          { text: `-${t.wrong}`, tone: "incorrect" },
          { text: `${t.score} / ${t.maxScore}`, strong: true },
        ]),
        emptyTable: "No PYQ sections attempted yet.",
        advice,
        action: drillFor(m, m.mistakes.find((x) => x.marksLost > 0)?.section ?? null),
      };
    }

    case "dailyAverage": {
      const days = m.studyTime.daily.slice(-windowDays);
      const total = days.reduce((s, d) => s + dayTotal(d), 0);
      const avg = Math.round(total / windowDays);
      const practice = days.reduce((s, d) => s + d.practiceSeconds, 0);
      const zeroDays = days.filter((d) => dayTotal(d) < MIN_ACTIVE_SECONDS).length;
      const best = days.reduce((x, d) => (dayTotal(d) > dayTotal(x) ? d : x), days[0]);
      const advice: string[] = [];
      if (total === 0) advice.push(`No study time recorded in the last ${windowDays} days. Open a lesson or a PYQ section to start logging time.`);
      else {
        const share = Math.round((practice / total) * 100);
        advice.push(
          share < 30
            ? `Only ${share}% of your study time is practice. Follow lessons with timed questions to turn learning into marks.`
            : `${share}% of your study time is practice and ${100 - share}% is learning.`
        );
        if (zeroDays > 0) advice.push(`${zeroDays} of the last ${windowDays} days had no study (under 2 minutes). Short daily sessions beat occasional long ones.`);
        if (best && dayTotal(best) > 0) advice.push(`Your biggest day was ${fmtDay(best.date)} with ${fmtDuration(dayTotal(best))}.`);
      }
      return {
        name: "Daily Study Average",
        icon: "clock",
        benchmark: "Study time = lessons + practice, recorded while you work",
        statusText: total === 0 ? "No study logged" : `${windowDays - zeroDays} active days`,
        statusType: total === 0 ? "warning" : "info",
        value: `${fmtDuration(avg)} / day`,
        valueNote: `${fmtDuration(total)} in total over the last ${windowDays} days.`,
        formula: `Daily average = total study time in the last ${windowDays} days ÷ ${windowDays}`,
        explanation:
          "Study time is recorded while a lesson, quiz or PYQ section is open. Learning = lessons; practice = quizzes, PYQ sections and lesson practice. Days without study count as zero.",
        calc: `${fmtDuration(total)} ÷ ${windowDays} days = ${fmtDuration(avg)} per day`,
        tableIntro: `Your study time per day (last ${windowDays} days):`,
        columns: DAY_COLUMNS,
        rows: dayRows(days),
        emptyTable: "",
        advice,
      };
    }

    case "weeklyVolume": {
      const week = m.studyTime.daily.slice(-7);
      const prev = m.studyTime.daily.slice(-14, -7);
      const total = m.studyTime.last7DaysSeconds;
      const prevTotal = prev.reduce((s, d) => s + dayTotal(d), 0);
      const advice: string[] = [];
      if (total === 0) advice.push("No study time in the last 7 days. Even 30 minutes a day adds up to 3.5 hours a week.");
      else if (prevTotal > 0) {
        const change = Math.round(((total - prevTotal) / prevTotal) * 100);
        advice.push(
          change >= 0
            ? `Up ${change}% on the previous 7 days (${fmtDuration(prevTotal)}).`
            : `Down ${-change}% on the previous 7 days (${fmtDuration(prevTotal)}). Plan fixed study slots for the coming week.`
        );
      } else advice.push("You studied more this week than the week before, when no time was recorded.");
      return {
        name: "Weekly Study Volume",
        icon: "calendar",
        benchmark: "Last 7 days including today",
        statusText: total === 0 ? "No study logged" : total >= prevTotal ? "Up on last week" : "Down on last week",
        statusType: total === 0 ? "warning" : total >= prevTotal ? "success" : "info",
        value: `${fmtDuration(total)} / week`,
        valueNote: `Previous 7 days: ${fmtDuration(prevTotal)}.`,
        formula: "Weekly volume = sum of study time over the last 7 days (today included)",
        explanation: "Study time is recorded while a lesson, quiz or PYQ section is open, split into learning (lessons) and practice (quizzes, PYQs, lesson practice).",
        calc: `${week.map((d) => fmtDuration(dayTotal(d))).join(" + ")} = ${fmtDuration(total)}`,
        tableIntro: "Your study time per day (last 7 days):",
        columns: DAY_COLUMNS,
        rows: dayRows(week),
        emptyTable: "",
        advice,
      };
    }

    case "consistency": {
      const days = m.studyTime.daily.slice(-14);
      const c = m.consistency;
      const missed = 14 - c.activeDaysLast14;
      const advice: string[] = [];
      if (c.activeDaysLast14 === 0) advice.push("No active days in the last 2 weeks. Study at least 2 minutes today to start.");
      else if (missed > 0) advice.push(`You missed ${missed} of the last 14 days. Each extra active day adds about 7 points to this score.`);
      else advice.push("You studied on every one of the last 14 days.");
      advice.push(`Consistency carries ${Math.round(m.readiness.weights.consistency * 100)}% of the weight in your readiness score.`);
      return {
        name: "Study Consistency",
        icon: "calendar",
        benchmark: "A day is active with at least 2 minutes of study",
        statusText: c.score >= 80 ? "Consistent" : c.score >= 50 ? "Irregular" : "Inconsistent",
        statusType: c.score >= 80 ? "success" : c.score >= 50 ? "info" : "warning",
        value: `${c.activeDaysLast14} / 14 days`,
        valueNote: `Consistency score: ${c.score}%.`,
        formula: "Consistency = active days in the last 14 ÷ 14 × 100",
        explanation: "A day counts as active when at least 2 minutes of study (lessons or practice) were recorded on it, in the app's timezone.",
        calc: `${c.activeDaysLast14} ÷ 14 × 100 = ${c.score}%`,
        tableIntro: "The last 14 days:",
        columns: DAY_COLUMNS,
        rows: dayRows(days),
        emptyTable: "",
        advice,
      };
    }

    case "streak": {
      const s = m.streak;
      const advice: string[] = [];
      if (!s.activeToday) advice.push(s.current > 0 ? `Study at least 2 minutes today to extend your ${s.current}-day streak.` : "Study at least 2 minutes today to start a new streak.");
      if (s.current > 0 && s.current >= s.best) advice.push("This is your best streak so far.");
      else if (s.best > 0) advice.push(`Your best streak is ${s.best} days; ${s.best - s.current + 1} more active day${s.best - s.current + 1 === 1 ? "" : "s"} in a row beats it.`);
      return {
        name: "Active Study Streak",
        icon: "flame",
        benchmark: `Best streak: ${s.best} day${s.best === 1 ? "" : "s"}`,
        statusText: s.activeToday ? "Active today" : s.current > 0 ? "Study today to keep it" : "No current streak",
        statusType: s.activeToday ? "success" : s.current > 0 ? "warning" : "info",
        value: `${s.current} day${s.current === 1 ? "" : "s"}`,
        valueNote: s.activeToday ? "Today already counts." : "Today does not count yet.",
        formula: "Streak = consecutive active days, counting back from today (or from yesterday if you have not studied yet today)",
        explanation: "A day is active with at least 2 minutes of recorded study. Best streak is the longest run of consecutive active days in your history.",
        calc: `${s.current} consecutive active day${s.current === 1 ? "" : "s"} ending ${s.activeToday ? "today" : "yesterday"}.`,
        tableIntro: "The last 14 days:",
        columns: DAY_COLUMNS,
        rows: dayRows(m.studyTime.daily.slice(-14)),
        emptyTable: "",
        advice,
      };
    }
  }
}

type IconTint = "blue" | "teal" | "violet" | "amber" | "coral";

