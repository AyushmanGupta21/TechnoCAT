#!/usr/bin/env node
// Generates db/migrations/0001_baseline.sql from the LIVE database schema (public schema).
// Run once against the current production database, review the output, commit it, then
// record it as applied there with:  node scripts/migrate.mjs --mark-applied 0001_baseline
//
// The output is idempotent (IF NOT EXISTS / guarded constraints) so it can also build a
// fresh database from scratch. Read-only: this script never modifies the database.

import fs from "node:fs";
import path from "node:path";
import pg from "pg";
import { ROOT, loadEnvFile, buildPoolConfig } from "./lib/db-env.mjs";

// Tables owned by later migrations or by the runner itself are excluded from the baseline.
const EXCLUDE = new Set([
  "schema_migrations",
  "analysis_views",
  "user_challenges",
  "community_posts",
  "community_comments",
  "community_post_upvotes",
  "community_saved_posts",
  "community_comment_upvotes",
  "community_reports",
  "community_moderation_logs",
]);

const q = (id) => `"${id.replace(/"/g, '""')}"`;

async function main() {
  loadEnvFile();
  const client = new pg.Client(buildPoolConfig());
  await client.connect();

  try {
    const tables = (
      await client.query(
        `SELECT c.oid, c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
         WHERE n.nspname = 'public' AND c.relkind = 'r' ORDER BY c.relname`
      )
    ).rows.filter((t) => !EXCLUDE.has(t.relname));

    const out = [
      "-- 0001_baseline.sql",
      `-- Generated by scripts/db-introspect.mjs on ${new Date().toISOString()} from the live database.`,
      "-- Core application tables that pre-date the migrations system.",
      "",
    ];

    // Only extensions the schema itself depends on; Supabase-managed ones (vault, pg_stat_statements, ...)
    // are provisioned by the platform and must not be recreated here.
    const extensions = (await client.query(`SELECT extname FROM pg_extension WHERE extname IN ('uuid-ossp', 'pgcrypto') ORDER BY extname`)).rows;
    for (const e of extensions) out.push(`CREATE EXTENSION IF NOT EXISTS ${q(e.extname)};`);
    if (extensions.length) out.push("");

    const sequences = (
      await client.query(
        `SELECT s.relname, t.relname AS owner_table FROM pg_class s JOIN pg_namespace n ON n.oid = s.relnamespace
         LEFT JOIN pg_depend d ON d.objid = s.oid AND d.deptype IN ('a', 'i')
         LEFT JOIN pg_class t ON t.oid = d.refobjid
         WHERE n.nspname = 'public' AND s.relkind = 'S' ORDER BY s.relname`
      )
    ).rows.filter((s) => !s.owner_table || !EXCLUDE.has(s.owner_table));
    for (const s of sequences) out.push(`CREATE SEQUENCE IF NOT EXISTS public.${q(s.relname)};`);
    if (sequences.length) out.push("");

    const fkStatements = [];

    for (const t of tables) {
      const cols = (
        await client.query(
          `SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull,
                  pg_get_expr(d.adbin, d.adrelid) AS default_expr
           FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
           WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`,
          [t.oid]
        )
      ).rows;

      const constraints = (
        await client.query(
          `SELECT conname, contype, pg_get_constraintdef(oid) AS def FROM pg_constraint
           WHERE conrelid = $1 ORDER BY contype, conname`,
          [t.oid]
        )
      ).rows;

      const lines = cols.map((c) => {
        let line = `  ${q(c.attname)} ${c.type}`;
        if (c.default_expr) line += ` DEFAULT ${c.default_expr}`;
        if (c.attnotnull) line += " NOT NULL";
        return line;
      });
      for (const con of constraints) {
        if (con.contype === "f") {
          fkStatements.push(
            `DO $$ BEGIN\n  ALTER TABLE public.${q(t.relname)} ADD CONSTRAINT ${q(con.conname)} ${con.def};\n` +
              `EXCEPTION WHEN duplicate_object THEN NULL; END $$;`
          );
        } else {
          lines.push(`  CONSTRAINT ${q(con.conname)} ${con.def}`);
        }
      }

      out.push(`CREATE TABLE IF NOT EXISTS public.${q(t.relname)} (\n${lines.join(",\n")}\n);`);

      const indexes = (
        await client.query(
          `SELECT i.indexname, i.indexdef FROM pg_indexes i
           WHERE i.schemaname = 'public' AND i.tablename = $1
             AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conname = i.indexname AND c.conrelid = $2)
           ORDER BY i.indexname`,
          [t.relname, t.oid]
        )
      ).rows;
      for (const idx of indexes) {
        out.push(idx.indexdef.replace(/^CREATE (UNIQUE )?INDEX /, "CREATE $1INDEX IF NOT EXISTS ") + ";");
      }
      out.push("");
    }

    if (fkStatements.length) {
      out.push("-- Foreign keys (added after all tables exist)");
      out.push(...fkStatements, "");
    }

    const dir = path.join(ROOT, "db", "migrations");
    fs.mkdirSync(dir, { recursive: true });
    const file = path.join(dir, "0001_baseline.sql");
    fs.writeFileSync(file, out.join("\n"));
    console.log(`Wrote ${path.relative(ROOT, file)} (${tables.length} tables).`);
  } finally {
    await client.end();
  }
}

main().catch((err) => {
  console.error(`Introspection error: ${err.message}`);
  process.exit(1);
});
